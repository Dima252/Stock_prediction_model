"""Build the static site: computes today's regime and bakes it into one HTML file.

Design choice: a single self-contained HTML file with the data embedded as JSON,
regenerated by the daily job. No server, no API, no database.

That is not laziness - it is forced by the strategy. `oversold_breadth` is a
property of the WHOLE universe on a given day, so a per-ticker request would have
to load all ~1500 names anyway. Precomputing the snapshot nightly and letting the
browser do the lookup is both simpler and faster than any backend.

Run after 13_forward_log.py (it reuses that script's price cache).
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.config import PROCESSED, REVERSION_EXIT
from src.live import JOURNAL, PRICE_CACHE, build_panel, drop_incomplete_last_bar
from src.setups import SETUPS

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
SITE.mkdir(exist_ok=True)

BREADTH_ON = 0.20          # the gate in s_market_drop
HISTORY_DAYS = 400


def jsonable(o):
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating,)):
        return None if not np.isfinite(o) else round(float(o), 6)
    if isinstance(o, (pd.Timestamp, datetime)):
        return pd.Timestamp(o).strftime("%Y-%m-%d")
    raise TypeError(type(o))


def main() -> None:
    print("=== loading panel ===")
    px = drop_incomplete_last_bar(pd.read_parquet(PRICE_CACHE))
    panel = build_panel(px)
    latest = panel["date"].max()
    today = panel[panel["date"] == latest].copy()
    print(f"latest complete session: {pd.Timestamp(latest).date()}  ({len(today):,} names)")

    # ---------------------------------------------------------------- regime
    daily = (panel.groupby("date")["oversold_breadth"].first()
                  .dropna().sort_index().tail(HISTORY_DAYS))
    breadth = float(daily.iloc[-1])
    active = breadth > BREADTH_ON
    pct_days_active = float((daily > BREADTH_ON).mean())
    print(f"oversold_breadth = {breadth:.3f}  -> {'ACTIVE' if active else 'DORMANT'}")

    # ------------------------------------------------------------ candidates
    mask = SETUPS["market_drop"](panel).fillna(False)
    fired_today = panel.loc[mask & (panel["date"] == latest)].copy()
    liq = fired_today["liquid"] if "liquid" in fired_today else True
    fired_today = fired_today[liq]
    cands = []
    for _, r in fired_today.iterrows():
        one_r = REVERSION_EXIT.stop_atr * r["atr14"]
        cands.append({"ticker": r["ticker"], "close": r["close"], "rsi2": r["rsi2"],
                      "resid": r["resid_ret5_atr"], "atr": r["atr14"],
                      "stop": r["close"] - one_r})
    print(f"candidates today: {len(cands)}")

    # --------------------------------------------------- per-ticker snapshot
    ev = pd.read_parquet(PROCESSED / "events.parquet")
    md = ev[ev.setup == "market_drop"]
    hist = (md.groupby("ticker")
              .agg(n=("r_net", "size"), mean_r=("r_net", "mean"),
                   win=("r_net", lambda s: float((s > 0).mean())))
              .to_dict("index"))
    uni = pd.read_parquet(PROCESSED / "universe.parquet").set_index("ticker")

    # Compact encoding. This file is regenerated and committed every night, so
    # its size becomes repository history. Three easy wins over the obvious
    # object-per-ticker form:
    #   - fixed-order arrays, so 12 key names are not repeated 1,500 times
    #   - sector strings interned into a lookup table
    #   - c2 dropped entirely: it is the market-wide gate, identical for every
    #     ticker, and already present as regime.active
    # Cuts the payload roughly threefold with no loss of information.
    fired_set = set(fired_today["ticker"])
    sectors, sec_idx = [], {}

    def _sec(name):
        if name not in sec_idx:
            sec_idx[name] = len(sectors); sectors.append(name)
        return sec_idx[name]

    def _r(v, nd=3):
        return None if v is None or not np.isfinite(v) else round(float(v), nd)

    def _b(cond, val):
        return None if pd.isna(val) else int(cond)

    tickers = {}
    for _, r in today.iterrows():
        tk = r["ticker"]
        h = hist.get(tk) or {}
        tickers[tk] = [
            _sec(uni["sector"].get(tk, "Unknown")),
            _r(r["close"], 2),
            _b(r["dist_sma200_atr"] > 0, r["dist_sma200_atr"]),
            _b(r["resid_ret5_atr"] > -0.5, r["resid_ret5_atr"]),
            _b(r["rsi2"] < 10, r["rsi2"]),
            _r(r["rsi2"], 1), _r(r["resid_ret5_atr"], 2), _r(r["dist_sma200_atr"], 2),
            int(tk in fired_set),
            h.get("n"), _r(h.get("mean_r")), _r(h.get("win"), 3),
        ]
    # field order for the browser, so the encoding is self-describing
    TFIELDS = ["sec", "close", "c1", "c3", "c4", "rsi2", "resid", "dist200",
               "fires", "hist_n", "hist_r", "hist_win"]
    print(f"ticker snapshot: {len(tickers):,} names, {len(sectors)} sectors")

    # ------------------------------------------------------- forward journal
    fwd = {}
    if JOURNAL.exists():
        j = pd.read_csv(JOURNAL, parse_dates=["signal_date"])
        c = j[(j.status == "CLOSED") & (j.signal_date > "2025-12-30")]
        if len(c):
            days = c.groupby("signal_date")["r_net"].mean()
            rng = np.random.default_rng(7)
            bm = days.to_numpy()[rng.integers(0, len(days), (4000, len(days)))].mean(axis=1)

            # Signal days cluster into EPISODES - one selloff spanning several
            # sessions is one market event, not several independent draws. This
            # is the honest picture of how few observations there really are.
            ds = np.sort(days.index.to_numpy())
            groups, cur = [], [ds[0]]
            for d in ds[1:]:
                if (pd.Timestamp(d) - pd.Timestamp(cur[-1])).days <= 5:
                    cur.append(d)
                else:
                    groups.append(cur); cur = [d]
            groups.append(cur)
            episodes = []
            for gp in groups:
                sub = c[c.signal_date.isin(gp)]
                episodes.append({"start": pd.Timestamp(gp[0]).strftime("%Y-%m-%d"),
                                 "end": pd.Timestamp(gp[-1]).strftime("%Y-%m-%d"),
                                 "days": len(gp), "trades": len(sub),
                                 "r": float(sub.r_net.mean())})

            per_day = (c.groupby("signal_date")
                        .agg(n=("r_net", "size"), r=("r_net", "mean"),
                             win=("r_net", lambda s: float((s > 0).mean())))
                        .reset_index().sort_values("signal_date", ascending=False))
            recent = [{"d": pd.Timestamp(r.signal_date).strftime("%Y-%m-%d"),
                       "n": int(r.n), "r": float(r.r), "win": float(r.win)}
                      for r in per_day.head(20).itertuples()]

            fwd = {"trades": len(c), "days": len(days),
                   "r_per_day": float(days.mean()),
                   "ci_lo": float(np.quantile(bm, .025)),
                   "ci_hi": float(np.quantile(bm, .975)),
                   "win_rate": float((c.r_net > 0).mean()),
                   "r_per_trade": float(c.r_net.mean()),
                   "hold": float(c.hold_days.mean()),
                   "open": int((j.status == "OPEN").sum()),
                   "pending": int((j.status == "PENDING_ENTRY").sum()),
                   "episodes": episodes, "recent": recent,
                   "start": str(c.signal_date.min().date())}

    snap = {
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        "session": pd.Timestamp(latest).strftime("%Y-%m-%d"),
        "regime": {"breadth": breadth, "threshold": BREADTH_ON, "active": active,
                   "pct_days_active": pct_days_active,
                   "history": [{"d": pd.Timestamp(d).strftime("%Y-%m-%d"),
                                "v": round(float(v), 4)} for d, v in daily.items()]},
        "candidates": cands,
        "tfields": TFIELDS,
        "sectors": sectors,
        "tickers": tickers,
        "forward": fwd,
    }

    out = SITE / "snapshot.json"
    out.write_text(json.dumps(snap, default=jsonable), encoding="utf-8")
    print(f"wrote {out}  ({out.stat().st_size/1024:.0f} KB)")

    tpl = (SITE / "template.html").read_text(encoding="utf-8")
    html = tpl.replace("/*__SNAPSHOT__*/null",
                       json.dumps(snap, default=jsonable, separators=(",", ":")))
    (SITE / "index.html").write_text(html, encoding="utf-8")
    print(f"wrote {SITE/'index.html'}  "
          f"({(SITE/'index.html').stat().st_size/1024:.0f} KB)")

    # docs/ is what GitHub Pages serves; .nojekyll stops Jekyll touching it
    docs = ROOT / "docs"
    docs.mkdir(exist_ok=True)
    (docs / "index.html").write_text(html, encoding="utf-8")
    (docs / ".nojekyll").write_text("", encoding="utf-8")
    print(f"wrote {docs/'index.html'}  ({(docs/'index.html').stat().st_size/1024:.0f} KB)")


if __name__ == "__main__":
    main()
